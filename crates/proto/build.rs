//! Bakes the product identity from `<repo>/brand.json` (the single source, M5 "Brand switch")
//! into `$OUT_DIR/brand.rs`, included as `agenthub_proto::brand`. Both the desktop app and the
//! `agenthub-hook` sidecar link this crate, so they always agree on folder names, exe names,
//! the hook marker and the pipe name.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set by cargo"));
    let brand_path = manifest_dir.join("..").join("..").join("brand.json");
    println!("cargo:rerun-if-changed={}", brand_path.display());

    let text = fs::read_to_string(&brand_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", brand_path.display()));
    let brand: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("{} is not valid JSON: {e}", brand_path.display()));

    let field = |key: &str| -> String {
        brand
            .get(key)
            .and_then(|v| v.as_str())
            .unwrap_or_else(|| panic!("brand.json: \"{key}\" must be a string"))
            .to_string()
    };
    let list = |key: &str| -> Vec<String> {
        brand
            .get("legacy")
            .and_then(|l| l.get(key))
            .and_then(|v| v.as_array())
            .unwrap_or_else(|| panic!("brand.json: \"legacy.{key}\" must be an array"))
            .iter()
            .map(|v| {
                v.as_str()
                    .unwrap_or_else(|| panic!("brand.json: \"legacy.{key}\" must hold strings"))
                    .to_string()
            })
            .collect()
    };

    let name = field("name");
    let slug = field("slug");
    let exe_prefix = field("exePrefix");
    for (key, value) in [("name", &name), ("identifier", &field("identifier")), ("publisher", &field("publisher"))] {
        assert!(!value.trim().is_empty(), "brand.json: \"{key}\" must not be empty");
    }
    // Both end up in folder, exe, pipe and mutex names.
    for (key, value) in [("slug", &slug), ("exePrefix", &exe_prefix)] {
        assert!(
            !value.is_empty() && value.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'),
            "brand.json: \"{key}\" must be non-empty lowercase ASCII letters, digits or '-'"
        );
    }

    let consts = [
        ("NAME", name.clone()),
        ("SLUG", slug),
        ("IDENTIFIER", field("identifier")),
        ("PUBLISHER", field("publisher")),
        ("EXE_PREFIX", exe_prefix.clone()),
        ("WEBSITE", field("website")),
        ("REPOSITORY", field("repository")),
        ("SUPPORT_EMAIL", field("supportEmail")),
        ("UPDATE_ENDPOINT", field("updateEndpoint")),
        ("HOOK_MARKER", format!("{exe_prefix}-hook")),
        ("HUB_EXE_STEM", format!("{exe_prefix}-hub")),
        ("LOG_FILE_STEM", exe_prefix.clone()),
    ];
    let mut out = String::from("// Generated by crates/proto/build.rs from brand.json. Do not edit.\n");
    for (key, value) in consts {
        out.push_str(&format!("pub const {key}: &str = {value:?};\n"));
    }
    out.push_str(&format!(
        "/// The desktop app's exe: the cargo binary (`<exePrefix>.exe`) and the bundled one (`<name>.exe`).\n\
         pub const DESKTOP_EXE_NAMES: [&str; 2] = [{:?}, {:?}];\n",
        format!("{exe_prefix}.exe"),
        format!("{name}.exe"),
    ));
    for (key, field) in [
        ("LEGACY_SLUGS", "slugs"),
        ("LEGACY_HOOK_MARKERS", "hookMarkers"),
        ("LEGACY_CREDENTIAL_PREFIXES", "credentialPrefixes"),
    ] {
        out.push_str(&format!("pub const {key}: &[&str] = &{:?};\n", list(field)));
    }

    let out_path = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set by cargo")).join("brand.rs");
    fs::write(&out_path, out).unwrap_or_else(|e| panic!("failed to write {}: {e}", out_path.display()));
}
